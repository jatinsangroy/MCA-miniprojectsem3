  const quizEl = $('quiz-content');
  hideEl('quiz-score-banner');
  hideEl('btn-next-quiz-round');
  hideEl('quiz-results');
  showFlex('quiz-header-actions');
  showBlock('practice-coding-card');
  showBlock('quiz-submit-card');

