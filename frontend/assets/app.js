async function runPracticeCode() {
  const code = $('practice-code-editor')?.value || '';
  if (!code.trim()) {
    showToast('Write some Python code first.', 'info');
    return;
  }

  const runBtn = $('btn-run-code');
  const statusEl = $('practice-status-badge');
  const outWrap = $('practice-output-wrap');
  const outPre = $('practice-code-output');

  runBtn.disabled = true;
  runBtn.textContent = '⏳ Running...';
  if (statusEl) statusEl.textContent = 'Executing in Python sandbox...';

  try {
    const res = await fetch(`${API_BASE}/run-code`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ code }),
    });
    const data = await res.json();
    showBlock('practice-output-wrap');
    const combined = (data.stdout || '') + (data.stderr ? `\n${data.stderr}` : '');
    outPre.textContent = combined.trim() || '(No output printed)';
    outPre.classList.toggle('has-error', data.exit_code !== 0);
    if (statusEl) {
      statusEl.textContent = data.exit_code === 0 ? '✓ Executed successfully (exit 0)' : `✗ Exited with code ${data.exit_code}`;
      statusEl.className = `text-sm ${data.exit_code === 0 ? 'text-green' : 'text-red'}`;
    }
  } catch (err) {
    showBlock('practice-output-wrap');
    outPre.textContent = `Error running code: ${err.message}`;
    outPre.classList.add('has-error');
  } finally {
    runBtn.disabled = false;
    runBtn.textContent = '▶ Run Code';
  }
}

function parseAssessmentMarkdown(md) {
  const questions = [];
  const answerKey = {};

  // Split off Answer Key and Adaptation Report so Answer Key stays hidden before submit
  const parts = md.split(/##\s+Answer Key/i);
  const quizSection = parts[0] || md;
  const afterQuiz = parts[1] || '';
  const answerKeySection = afterQuiz.split(/##\s+Adaptation Report/i)[0] || '';

  // Parse Answer Key lines (e.g. "- **Q1**: **B** — explanation" or "Q1: B - ...")
  const keyLines = answerKeySection.split('\n');
  let currentKeyQ = null;
  keyLines.forEach(line => {
    const m = line.match(/(?:^|\*|\s)Q(\d+)\*?\*?\s*[:\-–—]\s*(.+)/i);
    if (m) {
      const qId = `q${m[1]}`;
      currentKeyQ = qId;
      const rest = m[2].trim();
      const letterMatch = rest.match(/^(?:\*\*|`)?([A-D])(?:\*\*|`|\b|\))/i);
      answerKey[qId] = {
        raw: rest,
        letter: letterMatch ? letterMatch[1].toUpperCase() : null,
      };
    } else if (currentKeyQ && line.trim() && !line.trim().startsWith('#')) {
      answerKey[currentKeyQ].raw += ' ' + line.trim();
    }
  });

  // Parse Questions (### Q1 ... ### Q2 ...)
  const qBlocks = quizSection.split(/###\s+Q(\d+)/i);
  for (let i = 1; i < qBlocks.length; i += 2) {
    const qNum = qBlocks[i];
    const qId = `q${qNum}`;
    const block = qBlocks[i + 1] || '';
    const lines = block.split('\n');
    const headerLine = (lines[0] || '').trim();

    let type = 'short';
    if (/mcq|multiple/i.test(headerLine)) type = 'mcq';
    else if (/code/i.test(headerLine)) type = 'code';

    // Extract code snippet if present
    const codeMatch = block.match(/```(?:python|py|js|javascript)?\n([\s\S]*?)```/i);
    const starterCode = codeMatch ? codeMatch[1].trim() : '';
    if (starterCode && type !== 'mcq') type = 'code';

    // Extract MCQ options (- A) ... or A. ...)
    const options = [];
    const promptLines = [];
    let inCodeBlock = false;

    lines.slice(1).forEach(l => {
      if (l.trim().startsWith('```')) {
        inCodeBlock = !inCodeBlock;
        promptLines.push(l);
        return;
      }
      if (!inCodeBlock) {
        const optMatch = l.match(/^\s*(?:[-*]\s*)?(?:\*\*)?([A-D])(?:\)|\.)(?:\*\*)?\s+(.+)/);
        if (optMatch) {
          options.push({
            letter: optMatch[1].toUpperCase(),
            text: optMatch[2].replace(/\s*\(correct.*?\)/i, '').trim(),
            markedCorrect: /\(correct|\✓|\*\*/i.test(l),
          });
          return;
        }
      }
      promptLines.push(l);
    });

    if (options.length >= 2) type = 'mcq';

    // If Answer Key didn't specify a letter for MCQ, fallback to markedCorrect or 'B'
    if (type === 'mcq' && (!answerKey[qId] || !answerKey[qId].letter)) {
      const found = options.find(o => o.markedCorrect);
      answerKey[qId] = {
        raw: answerKey[qId]?.raw || `Correct option: ${found ? found.letter : 'B'}`,
        letter: found ? found.letter : 'B',
      };
    }

    questions.push({
      id: qId,
      num: Number(qNum),
      type,
      header: headerLine.replace(/^[:\-–—\s]+/, ''),
      promptMd: promptLines.join('\n').trim(),
      options,
      starterCode,
    });
  }

  return { questions, answerKey };
}

