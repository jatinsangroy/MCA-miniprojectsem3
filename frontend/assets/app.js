/* ── Toast ── */
function showToast(msg, type = 'info', duration = 4000) {
  const icons = {
    success: `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><path d="M9 12l2 2 4-4"/></svg>`,
    error:   `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><line x1="15" y1="9" x2="9" y2="15"/><line x1="9" y1="9" x2="15" y2="15"/></svg>`,
    info:    `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"/><line x1="12" y1="8" x2="12" y2="12"/><line x1="12" y1="16" x2="12.01" y2="16"/></svg>`,
  };
  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.innerHTML = `${icons[type] || icons.info}<span>${msg}</span>`;
  $('toast-container').appendChild(toast);
  setTimeout(() => toast.remove(), duration);
}

/* ── Markdown render ── */
function renderMarkdown(md) {
  if (!md) return '<p class="text-muted">No content available.</p>';
  if (typeof marked !== 'undefined') {
    return marked.parse(md);
  }
  // Basic fallback
  return md.split('\n').map(l => {
    if (l.startsWith('# '))  return `<h1>${l.slice(2)}</h1>`;
    if (l.startsWith('## ')) return `<h2>${l.slice(3)}</h2>`;
    if (l.startsWith('### '))return `<h3>${l.slice(4)}</h3>`;
    if (l.startsWith('- '))  return `<li>${l.slice(2)}</li>`;
    if (l.startsWith('**') && l.endsWith('**')) return `<strong>${l.slice(2,-2)}</strong>`;
    return l ? `<p>${l}</p>` : '';
  }).join('');
}

